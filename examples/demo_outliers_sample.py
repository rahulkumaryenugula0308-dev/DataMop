import pandas as pd

from datamop.outliers import OutlierHandler


# ==================================================
# Create Sample Data
# ==================================================

data = {
    "Age": [
        20,
        21,
        22,
        23,
        24,
        25,
        26,
        27,
        28,
        150
    ],

    "Salary": [
        30000,
        32000,
        35000,
        34000,
        36000,
        38000,
        39000,
        40000,
        41000,
        500000
    ]
}


df = pd.DataFrame(data)


print("========== ORIGINAL DATA ==========")

print(df)


# ==================================================
# Create Handler
# ==================================================

handler = OutlierHandler(df)


# ==================================================
# IQR Report
# ==================================================

handler.display_iqr_report()


# ==================================================
# Remove IQR Outliers
# ==================================================

handler.remove_iqr_outliers()


# ==================================================
# Display Clean Data
# ==================================================

print("\n========== AFTER OUTLIER REMOVAL ==========")

print(handler.df)


# ==================================================
# Display Log
# ==================================================

handler.display_log()